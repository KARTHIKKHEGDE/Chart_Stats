-- Admin-visible user activity history.
-- Run once in the Supabase SQL editor for the app's project.
create table if not exists public.user_activity (
    id bigint generated by default as identity primary key,
    user_name text not null,
    action text not null,
    page text not null default '',
    label text not null default '',
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists user_activity_user_id_idx
    on public.user_activity (user_name, id desc);

alter table public.user_activity enable row level security;
revoke all on public.user_activity from anon, authenticated;
grant select, insert on public.user_activity to service_role;
grant usage, select on sequence public.user_activity_id_seq to service_role;
