-- Audit SEC keyword searches so they appear in the admin search history.
create table if not exists public.keyword_searches (
  id bigint generated by default as identity primary key,
  user_name text not null,
  keyword text not null,
  start_date date not null,
  end_date date not null,
  forms text,
  time_ist timestamp without time zone not null,
  date_ist date not null,
  created_at timestamptz not null default now()
);

create index if not exists keyword_searches_date_ist_idx
  on public.keyword_searches (date_ist);
create index if not exists keyword_searches_user_name_idx
  on public.keyword_searches (user_name);

alter table public.keyword_searches enable row level security;

-- The application accesses this audit table through its server-side service key.
-- No direct client access policies are created.
